const ROLE_ALLOWED = {
  director: new Set(['dashboard','children','child','groups','group','calendar','lesson','payments','refunds','balances','teachers','sites','salary','rent','partner','stats','settings']),
  partner: new Set(['dashboard','children','child','groups','group','calendar','lesson','payments','refunds','balances','teachers','sites','salary','settlements']),
  teacher: new Set(['teacherToday','teacherCalendar','teacherLesson']),
};

function mergeTopic(base, override) {
  if (!base) return override ?? null;
  if (!override) return base;
  const sections = { ...(base.sections ?? {}) };
  for (const [key, value] of Object.entries(override.sections ?? {})) {
    sections[key] = [...(sections[key] ?? []), ...(value ?? [])];
  }
  return { ...base, ...override, title: override.title ?? base.title, sections };
}

export function getContextHelp(role, page) {
  const normalizedRole = String(role ?? '');
  const normalizedPage = String(page ?? '');
  if (!ROLE_ALLOWED[normalizedRole]?.has(normalizedPage)) return null;
  return mergeTopic(COMMON_HELP[normalizedPage] ?? null, ROLE_HELP[normalizedRole]?.[normalizedPage] ?? null);
}

function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (symbol) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[symbol]);
}

export function renderContextHelpHtml(help, { temporaryTeacher = false } = {}) {
  if (!help) return '';
  const sections = Object.entries(help.sections ?? {})
    .filter(([, items]) => Array.isArray(items) && items.length)
    .map(([key, items]) => `<section class="context-help-section"><h3>${escapeHtml(SECTION_TITLES[key] ?? key)}</h3><ul>${items.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}</ul></section>`)
    .join('');
  const temporary = temporaryTeacher
    ? '<div class="notice context-help-temporary">Сейчас вы просматриваете интерфейс преподавателя. Кнопка «Вернуться на главную» возвращает в административный интерфейс.</div>'
    : '';
  return `<div class="context-help-dialog-head"><h2 id="context-help-title">${escapeHtml(help.title)}</h2><button class="context-help-close" type="button" aria-label="Закрыть справку" title="Закрыть">×</button></div><div class="context-help-scroll">${temporary}${sections}</div><div class="context-help-actions"><button class="btn primary context-help-done" type="button">Закрыть</button></div>`;
}

let lastFocused = null;

function currentState() {
  return window.icubeLegacy?.state ?? null;
}

function isTemporaryTeacherView(state) {
  if (state?.role !== 'teacher') return false;
  const roles = state?.authUser?.roles ?? [];
  return roles.includes('director') || roles.includes('partner');
}

export function closeContextHelp() {
  if (typeof document === 'undefined') return;
  document.querySelector('.context-help-backdrop')?.remove();
  document.body?.classList?.remove('context-help-open');
  if (lastFocused && typeof lastFocused.focus === 'function') lastFocused.focus();
  lastFocused = null;
}

export function openContextHelp() {
  if (typeof document === 'undefined' || typeof window === 'undefined') return false;
  const state = currentState();
  const help = getContextHelp(state?.role, state?.page);
  if (!help) return false;
  closeContextHelp();
  lastFocused = document.activeElement;
  const backdrop = document.createElement('div');
  backdrop.className = 'context-help-backdrop';
  backdrop.innerHTML = `<div class="context-help-modal" role="dialog" aria-modal="true" aria-labelledby="context-help-title">${renderContextHelpHtml(help, { temporaryTeacher: isTemporaryTeacherView(state) })}</div>`;
  backdrop.addEventListener('click', (event) => {
    if (event.target === backdrop) closeContextHelp();
  });
  backdrop.querySelector('.context-help-close')?.addEventListener('click', closeContextHelp);
  backdrop.querySelector('.context-help-done')?.addEventListener('click', closeContextHelp);
  document.body.appendChild(backdrop);
  document.body.classList.add('context-help-open');
  backdrop.querySelector('.context-help-close')?.focus();
  return true;
}

function makeHelpButton(page) {
  const button = document.createElement('button');
  button.type = 'button';
  button.className = 'context-help-button';
  button.dataset.helpPage = page;
  button.textContent = '?';
  button.setAttribute('aria-label', 'Справка по странице');
  button.setAttribute('title', 'Справка');
  button.addEventListener('click', openContextHelp);
  return button;
}

function titleHeadingForPage(state) {
  if (!state) return null;
  const app = document.querySelector('#app');
  if (!app) return null;
  if (state.role === 'teacher') {
    if (state.page === 'teacherCalendar') return app.querySelector('.teacher-content .calendar-page-head h1');
    return app.querySelector('.teacher-content h1');
  }
  return app.querySelector('.content .page-head h1') ?? app.querySelector('.content .calendar-page-head h1');
}

function placeHelpButton(state, heading) {
  const existing = document.querySelector('.context-help-button');
  if (existing && existing.dataset.helpPage === String(state.page) && existing.parentElement?.contains(heading)) return;
  document.querySelectorAll('.context-help-button').forEach((button) => button.remove());
  document.querySelectorAll('.context-help-title-row').forEach((row) => {
    const h1 = row.querySelector('h1');
    if (h1 && row.parentElement) row.parentElement.insertBefore(h1, row);
    row.remove();
  });
  if (!heading?.parentElement) return;
  const row = document.createElement('div');
  row.className = 'context-help-title-row';
  heading.parentElement.insertBefore(row, heading);
  row.appendChild(heading);
  row.appendChild(makeHelpButton(String(state.page)));
}

export function syncContextHelpButton() {
  if (typeof document === 'undefined' || typeof window === 'undefined') return;
  const state = currentState();
  if (!getContextHelp(state?.role, state?.page)) {
    document.querySelectorAll('.context-help-button').forEach((button) => button.remove());
    return;
  }
  const heading = titleHeadingForPage(state);
  if (!heading) return;
  placeHelpButton(state, heading);
}

